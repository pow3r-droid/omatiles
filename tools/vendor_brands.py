#!/usr/bin/env python3
"""Vendor the brand logos the dock uses from a Simple Icons package (CC0).

    npm pack simple-icons@<version> && tar -xzf simple-icons-<version>.tgz
    python3 tools/vendor_brands.py package/

Writes Brands.js (one 24 x 24 path per logo) and brands/ (license, disclaimer,
provenance). Only the slugs below are kept; Glyphs.js maps apps to them.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

SLUGS = '''
1password alacritty androidstudio anki anthropic audacity basecamp bitwarden blender bluesky brave
claude cursor dbeaver discord docker element facebook figma filezilla firefoxbrowser ghostty gimp github
gitlab gnometerminal googlechrome googlegemini hey homeassistant hp inkscape instagram intellijidea kdenlive
keepassxc krita libreoffice localsend mastodon messenger mpv neovim nextcloud notion obsidian obsstudio
ollama opera perplexity postman protonmail protonvpn pycharm qbittorrent reddit signal spotify steam
syncthing tailscale telegram threads thunderbird tmux transmission twitch vim vivaldi vlcmediaplayer
vscodium warp wezterm whatsapp x youtube youtubemusic zenbrowser zoom zotero
'''.split()

def main(package):
    package = Path(package)
    version = json.loads((package / 'package.json').read_text())['version']
    out, sums = {}, []
    for slug in SLUGS:
        svg = (package / 'icons' / (slug + '.svg')).read_text()
        paths = re.findall(r'<path d="([^"]+)"', svg)
        if len(paths) != 1 or 'viewBox="0 0 24 24"' not in svg:
            sys.exit('%s: expected one path on a 24 x 24 view box' % slug)
        out[slug] = paths[0]
        sums.append('%s  %s.svg' % (hashlib.sha256(svg.encode()).hexdigest(), slug))
    root = Path(__file__).resolve().parent.parent
    body = ',\n'.join('    %s: %s' % (json.dumps(k), json.dumps(v)) for k, v in out.items())
    (root / 'Brands.js').write_text(
        '// Brand logos from Simple Icons %s (CC0; trademarks belong to their owners).\n'
        '// Generated by tools/vendor_brands.py; see brands/VENDORED.txt. One path each, 24 x 24.\n'
        'var PATHS = {\n%s\n};\n'
        "if (typeof module !== 'undefined') module.exports = {PATHS: PATHS};\n" % (version, body))
    brands = root / 'brands'
    brands.mkdir(exist_ok=True)
    (brands / 'LICENSE.md').write_text((package / 'LICENSE.md').read_text())
    (brands / 'DISCLAIMER.md').write_text((package / 'DISCLAIMER.md').read_text())
    (brands / 'VENDORED.txt').write_text(
        'Simple Icons %s (https://github.com/simple-icons/simple-icons), npm package simple-icons@%s.\n'
        'Only the paths of the icons listed below are kept, in Brands.js, by tools/vendor_brands.py.\n'
        'CC0 1.0 (LICENSE.md). The logos are trademarks of their owners (DISCLAIMER.md).\n\n'
        'sha256 of each source icon:\n%s\n' % (version, version, '\n'.join(sums)))
    print('%d logos from Simple Icons %s' % (len(out), version))

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'package')
